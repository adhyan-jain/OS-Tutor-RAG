"""Drive the real tutoring engine (no models) and print a transcript for the report.

Run from the repo root:  PYTHONPATH=. .venv/bin/python submission/build/transcript.py
RAG answers are generated by the model at run time, so a placeholder stands in
for them here; every tutor line (path, question, grading, hint, chips) is real
engine output.
"""
import json
from src.tutor import conversation as conv, engine
from src.tutor.engine import Reply, RagPlan

ANSWER = "[grounded answer streamed by the model from the retrieved slides]"
SOURCES = [{"metadata": {"slide_title": "Process Abstraction / What is a process?"}}]
s = conv.TutorState()
log = []

def student(msg): log.append(("Student", msg))
def tutor(text, chips=None):
    log.append(("Tutor", text)); 
    if chips: log.append(("chips", chips))

def turn(msg):
    student(msg)
    r = engine.plan_turn(s, msg)
    if isinstance(r, Reply):
        tutor(r.text, r.ui.get("chips")); return r
    fin = engine.finish_rag(s, r, message=msg, sources=SOURCES)
    tutor((r.lead + "\n\n" if r.lead else "") + ANSWER + fin.text, fin.ui.get("chips")); return fin

r = turn("I'm new to operating systems")
r = turn(r.ui["chips"][0])                 # taps the first suggestion exactly as typed
q = engine.K.question_by_id[s.pending["question_id"]]
r = turn("no idea")                         # unsure -> scaffold, never a bare 'wrong'
r = turn("hint")
r = turn("It hides the hardware behind a simple abstraction, and lets many programs share it safely without interfering.")
r = turn("I'm so confused by threads")
r = turn("Test my understanding of paging")
json.dump(log, open("submission/build/transcript.json", "w"), indent=1)
for who, x in log:
    print(f"{who}: {x}\n")
